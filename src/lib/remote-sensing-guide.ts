export type RemoteSensingKey = keyof typeof REMOTE_SENSING_GUIDE;

/** 兼容图层使用的大写缩写和农业面板的小写缩写，避免打开错误的说明条目。 */
export function getRemoteSensingKey(value?: string | null): RemoteSensingKey {
    const key = value?.toLowerCase();
    return key && Object.prototype.hasOwnProperty.call(REMOTE_SENSING_GUIDE, key)
        ? key as RemoteSensingKey
        : "ndvi";
}

